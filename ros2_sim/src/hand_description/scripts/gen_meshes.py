#!/usr/bin/env python3
"""Generate the hand's visual meshes (smooth-shaded OBJ, numpy only; procedural, no external models).

    python3 scripts/gen_meshes.py          # writes ../meshes/*.obj

Fingers/thumb: slightly tapered rounded capsules along +Z of their link (small gap at each joint).
Palm: rounded box. Thenar pad: ellipsoid. Forearm: long tapered elliptical shell with a wrist cuff. Wrist: ball joint dome + neck.
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(__file__))
import dims  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "meshes")
N_AROUND = 40


def write_obj(path, verts, normals, faces):
    with open(path, "w") as f:
        f.write("# generated by scripts/gen_meshes.py\n")
        for v in verts:
            f.write("v %.6f %.6f %.6f\n" % tuple(v))
        for n in normals:
            f.write("vn %.5f %.5f %.5f\n" % tuple(n))
        for a, b, c in faces:
            f.write(f"f {a+1}//{a+1} {b+1}//{b+1} {c+1}//{c+1}\n")


def lathe(profile, n=N_AROUND):
    """profile: list of (a, b, z) rings (elliptical radii a (x), b (y)) from bottom to top. Returns verts, normals, faces."""
    prof = np.asarray(profile, float)
    th = np.linspace(0, 2 * np.pi, n, endpoint=False)
    V = np.zeros((len(prof), n, 3))
    for i, (a, b, z) in enumerate(prof):
        V[i, :, 0], V[i, :, 1], V[i, :, 2] = a * np.cos(th), b * np.sin(th), z
    faces = []
    idx = lambda i, j: i * n + (j % n)
    for i in range(len(prof) - 1):
        for j in range(n):
            faces += [(idx(i, j), idx(i + 1, j), idx(i, j + 1)), (idx(i, j + 1), idx(i + 1, j), idx(i + 1, j + 1))]
    return finish(V.reshape(-1, 3), faces)


def finish(verts, faces):
    """Drop degenerate triangles, orient faces outward, compute smooth area-weighted vertex normals."""
    verts = np.asarray(verts)
    keep = []
    for f in faces:
        a, b, c = verts[list(f)]
        if np.linalg.norm(np.cross(b - a, c - a)) > 1e-12:
            keep.append(f)
    faces = np.array(keep)
    tri = verts[faces]
    fn = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
    centroid = verts.mean(axis=0)
    if np.sum(np.einsum("ij,ij->i", fn, tri.mean(axis=1) - centroid)) < 0:   # inward -> flip
        faces = faces[:, ::-1]
        fn = -fn
    normals = np.zeros_like(verts)
    for k in range(3):
        np.add.at(normals, faces[:, k], fn)
    norm = np.linalg.norm(normals, axis=1, keepdims=True)
    normals = normals / np.maximum(norm, 1e-12)
    return verts, normals, faces


def capsule_profile(r0, r1, z0, z1, round0=None, round1=None):
    """Tapered capsule from z0 to z1 with rounded ends (rings of circular cross-section)."""
    rb = r0 * 0.45 if round0 is None else round0
    rt = r1 * 0.85 if round1 is None else round1
    pts = [(0.0, z0)]
    for a in np.linspace(-np.pi / 2, 0, 7):
        pts.append((r0 - rb + rb * np.cos(a), z0 + rb + rb * np.sin(a)))
    for a in np.linspace(0, np.pi / 2, 9):
        pts.append((r1 - rt + rt * np.cos(a), z1 - rt + rt * np.sin(a)))
    pts.append((0.0, z1))
    return [(r, r, z) for r, z in pts]


def rounded_box(half, rr, n=44):
    """Rounded box centred on the origin, analytic normals. Face grids are denser near the edges."""
    h = np.asarray(half, float)
    inner = h - rr
    t = np.linspace(-1, 1, n)
    t = np.sign(t) * np.abs(t) ** 0.8
    V, N, F = [], [], []
    for axis in range(3):
        u, v = [k for k in range(3) if k != axis]
        for sign in (-1, 1):
            base = len(V)
            for a in t:
                for b in t:
                    c = np.zeros(3)
                    c[axis], c[u], c[v] = sign * h[axis], a * h[u], b * h[v]
                    q = np.clip(c, -inner, inner)
                    d = c - q
                    nd = np.linalg.norm(d)
                    p = q + rr * d / nd if nd > 1e-12 else c
                    V.append(p)
                    N.append(d / nd if nd > 1e-12 else np.sign(c) * (np.abs(c) == np.abs(c).max()))
            for i in range(n - 1):
                for j in range(n - 1):
                    a0, a1, a2, a3 = base + i * n + j, base + i * n + j + 1, base + (i + 1) * n + j, base + (i + 1) * n + j + 1
                    F += [(a0, a2, a1), (a1, a2, a3)]
    V, N, F = np.array(V), np.array(N, float), np.array(F)
    tri = V[F]
    fn = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
    flip = np.einsum("ij,ij->i", fn, tri.mean(axis=1)) < 0     # box centred at the origin: outward = away from it
    F[flip] = F[flip][:, ::-1]
    return V, N, F


def ellipsoid(radii, nu=36, nv=18):
    prof = []
    for v in np.linspace(-np.pi / 2, np.pi / 2, nv):
        prof.append((radii[0] * np.cos(v), radii[1] * np.cos(v), radii[2] * np.sin(v)))
    return lathe(prof, nu)


def forearm():
    L, (a0, b0), (a1, b1) = dims.FOREARM["length"], dims.FOREARM["wrist_ab"], dims.FOREARM["bottom_ab"]
    prof = [(0.0, 0.0, 0.0)]
    zs = np.linspace(0, -L, 40)
    for z in zs:
        u = -z / L
        s = u * u * (3 - 2 * u)                      # smooth taper: slim at the wrist, full near the elbow end
        a, b = a0 + (a1 - a0) * s, b0 + (b1 - b0) * s
        if u > 0.96:                                 # round the bottom edge
            k = (u - 0.96) / 0.04
            a, b = a * (1 - 0.12 * k * k), b * (1 - 0.12 * k * k)
        prof.append((a, b, z))
    prof.append((0.0, 0.0, -L))
    return lathe(prof)


def cuff():
    (z0, z1), (a, b) = dims.FOREARM["cuff"]["z"], dims.FOREARM["cuff"]["ab"]
    e = 0.004
    prof = [(0, 0, z0), (a - e, b - e, z0)]
    for t in np.linspace(-np.pi / 2, 0, 5)[1:]:
        prof.append((a - e + e * np.cos(t), b - e + e * np.cos(t), z0 + e + e * np.sin(t)))
    for t in np.linspace(0, np.pi / 2, 5)[1:]:
        prof.append((a - e + e * np.cos(t), b - e + e * np.cos(t), z1 - e + e * np.sin(t)))
    prof.append((0, 0, z1))
    return lathe(prof)


def wrist():
    """Wrist ball joint in the PALM frame: a dome sitting on the forearm's top face (pivot at z = -WRIST_PIVOT) and a neck up
    into the palm. A sphere about the pivot, so it never touches the forearm whatever the wrist angles are."""
    R, rn, zc = dims.WRIST_BALL["radius"], dims.WRIST_BALL["neck_radius"], -dims.WRIST_PIVOT
    t1 = np.arccos(rn / R)
    prof = [(0.0, 0.0, zc - 0.002), (R, R, zc - 0.002), (R, R, zc)]
    for t in np.linspace(0, t1, 8)[1:]:
        prof.append((R * np.cos(t), R * np.cos(t), zc + R * np.sin(t)))
    prof.append((rn, rn, 0.004))
    prof.append((0.0, 0.0, 0.004))
    return lathe(prof)


def main():
    os.makedirs(OUT, exist_ok=True)
    g = dims.GAP
    for name, f in dims.FINGERS.items():
        for part, L, (r0, r1) in zip(("prox", "mid", "dist"), f["lengths"], dims.segment_radii(name)):
            tip = part == "dist"
            write_obj(f"{OUT}/{name}_{part}.obj", *lathe(capsule_profile(r0, r1, g, L - (0 if tip else g), round1=r1 * (0.9 if tip else 0.5))))
    for part, L, (r0, r1) in zip(("meta", "prox", "dist"), dims.THUMB["lengths"], dims.THUMB["radii"]):
        z0 = 0.0 if part == "meta" else g                 # the metacarpal's base is the CMC ball
        write_obj(f"{OUT}/thumb_{part}.obj", *lathe(capsule_profile(r0, r1, z0, L - (0 if part == "dist" else g),
                                                                 round0=r0 * 0.95 if part == "meta" else None,
                                                                 round1=r1 * (0.9 if part == "dist" else 0.5))))
    write_obj(f"{OUT}/palm.obj", *rounded_box(dims.PALM["half"], dims.PALM["round"]))
    write_obj(f"{OUT}/thenar.obj", *ellipsoid(dims.PAD["radii"]))
    write_obj(f"{OUT}/forearm.obj", *forearm())
    write_obj(f"{OUT}/cuff.obj", *cuff())
    write_obj(f"{OUT}/wrist.obj", *wrist())
    print("wrote", len(os.listdir(OUT)), "meshes to", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
